#!/usr/bin/env bash
# Bybit V5 API wrapper. All trading API calls go through here.
# Usage: bash scripts/bybit.sh <subcommand> [args...]
#
# Auth (V5): X-BAPI-SIGN = HMAC_SHA256(timestamp + apiKey + recvWindow + payload)
# where payload is the raw query string (GET) or the raw JSON body (POST).
# The signed string must match the request BYTE FOR BYTE — so we build the
# query string once and reuse it for both the signature and the URL.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"

# .env is a FALLBACK, not an override: a value already exported in the
# environment must win, or `BYBIT_ENDPOINT=... bash scripts/bybit.sh ...` is
# silently ignored and every "which host is this key valid on?" test answers
# for whichever host .env names. Snapshot the pre-existing values, source, then
# restore whatever was already set.
if [[ -f "$ENV_FILE" ]]; then
  _pre_endpoint="${BYBIT_ENDPOINT:-}"
  _pre_recv="${BYBIT_RECV_WINDOW:-}"
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
  [[ -n "$_pre_endpoint" ]] && BYBIT_ENDPOINT="$_pre_endpoint"
  [[ -n "$_pre_recv" ]] && BYBIT_RECV_WINDOW="$_pre_recv"
  unset _pre_endpoint _pre_recv
fi

# env.template ships "your_..._here" placeholders. They are NON-EMPTY, so a naive
# -z check would pass them through to the API and produce a 401 instead of the
# intended graceful fallback. Normalize any placeholder value to empty.
for _v in BYBIT_API_KEY BYBIT_API_SECRET PERPLEXITY_API_KEY PERPLEXITY_MODEL \
          CLICKUP_API_KEY CLICKUP_WORKSPACE_ID CLICKUP_CHANNEL_ID; do
  case "${!_v:-}" in
    your_*_here) unset "$_v" ;;
  esac
done
unset _v

: "${BYBIT_API_KEY:?BYBIT_API_KEY not set in environment}"
: "${BYBIT_API_SECRET:?BYBIT_API_SECRET not set in environment}"

# Demo Trading is a separate host from mainnet and from testnet. Demo keys are
# ONLY valid on api-demo.bybit.com; sending them to api.bybit.com returns 10003.
API="${BYBIT_ENDPOINT:-https://api-demo.bybit.com}"
RECV="${BYBIT_RECV_WINDOW:-10000}"

# _sign runs inside $(...), so anything it assigns dies with the subshell. The
# timestamp must be generated by the CALLER and passed in, because the exact
# same value has to go into both the signature and the X-BAPI-TIMESTAMP header.
_now() { python -c 'import time;print(int(time.time()*1000))'; }

_sign() {  # _sign <timestamp> <payload>
  local ts="$1" payload="$2"
  printf '%s' "${ts}${BYBIT_API_KEY}${RECV}${payload}" \
    | openssl dgst -sha256 -hmac "$BYBIT_API_SECRET" -r \
    | cut -d' ' -f1
}

_get() {  # _get <path> [querystring]
  local path="$1" qs="${2:-}" ts sig
  ts="$(_now)"; sig="$(_sign "$ts" "$qs")"
  curl --fail-with-body -sS \
    -H "X-BAPI-API-KEY: $BYBIT_API_KEY" \
    -H "X-BAPI-TIMESTAMP: $ts" \
    -H "X-BAPI-RECV-WINDOW: $RECV" \
    -H "X-BAPI-SIGN: $sig" \
    "$API$path${qs:+?$qs}"
}

_post() {  # _post <path> <json-body>
  local path="$1" body="$2" ts sig
  ts="$(_now)"; sig="$(_sign "$ts" "$body")"
  curl --fail-with-body -sS \
    -H "X-BAPI-API-KEY: $BYBIT_API_KEY" \
    -H "X-BAPI-TIMESTAMP: $ts" \
    -H "X-BAPI-RECV-WINDOW: $RECV" \
    -H "X-BAPI-SIGN: $sig" \
    -H "Content-Type: application/json" \
    -X POST -d "$body" "$API$path"
}

_public() {  # _public <path> [querystring] — market data needs no auth
  local path="$1" qs="${2:-}"
  curl --fail-with-body -sS "$API$path${qs:+?$qs}"
}

cmd="${1:-}"
shift || true

case "$cmd" in
  account)
    # UNIFIED account: totalEquity, totalWalletBalance, and the per-coin list.
    _get /v5/account/wallet-balance "accountType=UNIFIED"
    ;;
  balance)
    coin="${1:-USDT}"
    _get /v5/account/wallet-balance "accountType=UNIFIED&coin=$coin"
    ;;
  positions)
    # Spot holdings are coin balances, not "positions" — /v5/position/list is
    # derivatives-only and returns empty for spot. Use `account` for holdings.
    _get /v5/position/list "category=linear&settleCoin=USDT"
    ;;
  quote)
    sym="${1:?usage: quote BTCUSDT}"
    _public /v5/market/tickers "category=spot&symbol=$sym"
    ;;
  tickers)
    # Whole spot universe with 24h % change — the screen's cheapest first pass.
    _public /v5/market/tickers "category=spot"
    ;;
  bars)
    # Bybit caps `limit` at 1000 per call and returns NEWEST FIRST (index 0 is
    # the most recent bar) — the reverse of Alpaca. Reverse before computing
    # any indicator that assumes chronological order.
    sym="${1:?usage: bars BTCUSDT [interval] [limit]}"
    iv="${2:-D}"; lim="${3:-200}"
    _public /v5/market/kline "category=spot&symbol=$sym&interval=$iv&limit=$lim"
    ;;
  instruments)
    # basePrecision / minOrderQty / minOrderAmt live here. A buy that violates
    # them is rejected with 170136/170140 — always check before sizing.
    sym="${1:-}"
    _public /v5/market/instruments-info "category=spot${sym:+&symbol=$sym}"
    ;;
  fee)
    sym="${1:?usage: fee BTCUSDT}"
    _get /v5/account/fee-rate "category=spot&symbol=$sym"
    ;;
  orders)
    # Open/untriggered only. Resting TP/SL orders appear here too.
    _get /v5/order/realtime "category=spot&limit=50"
    ;;
  history)
    lim="${1:-50}"
    _get /v5/order/history "category=spot&limit=$lim"
    ;;
  fills)
    # Paginated. Bybit returns a nextPageCursor; the ledger builder follows it
    # so the book's realized P&L is never computed from a truncated fill list.
    lim="${1:-100}"; cur="${2:-}"
    _get /v5/execution/list "category=spot&limit=$lim${cur:+&cursor=$cur}"
    ;;
  order)
    body="${1:?usage: order '<json>'}"
    _post /v5/order/create "$body"
    ;;
  amend)
    body="${1:?usage: amend '<json>'}"
    _post /v5/order/amend "$body"
    ;;
  cancel)
    body="${1:?usage: cancel '{\"category\":\"spot\",\"symbol\":\"BTCUSDT\",\"orderId\":\"...\"}'}"
    _post /v5/order/cancel "$body"
    ;;
  cancel-all)
    sym="${1:-}"
    _post /v5/order/cancel-all "{\"category\":\"spot\"${sym:+,\"symbol\":\"$sym\"}}"
    ;;
  demo-funds)
    # Demo Trading only: top the play account back up. Ignored on mainnet.
    coin="${1:-USDT}"; amt="${2:-200}"
    _post /v5/account/demo-apply-money \
      "{\"adjustType\":0,\"utaDemoApplyMoney\":[{\"coin\":\"$coin\",\"amountStr\":\"$amt\"}]}"
    ;;
  *)
    echo "Usage: bash scripts/bybit.sh <account|balance|positions|quote|tickers|bars|instruments|fee|orders|history|fills|order|amend|cancel|cancel-all|demo-funds> [args]" >&2
    exit 1
    ;;
esac
echo
